#!/usr/bin/env python3
"""
Plot Patient Trajectory
=======================

This script provides a comprehensive visualization of a patient's trajectory,
combining physiological waveform data with medication administration records.
It is designed to work with the data generated by `create_ic_p_mimic.py`.

Key Features:
- Loads full, resampled waveform data from one or more Parquet files.
- Handles non-contiguous waveform records and displays time gaps correctly.
- Loads medication tensor data and aligns it accurately using ICU admission time.
- Loads all t0 timestamps from the waveform files.
- Generates multi-panel plots for clear visualization:
  - Top panel: Key physiological signals (e.g., ABP Mean, CVP, HR).
  - Bottom panel: Medication administration over time as a stem plot.
- Marks all t0 timestamps for a given admission as vertical lines.

Usage:
    python -m src.plotting.plot_patient_trajectory --hadm_id <HADM_ID>
"""

import argparse
import warnings
from pathlib import Path

import matplotlib.dates as mdates
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import torch

# --- Suppress Matplotlib's UserWarning about locator INFO ---
warnings.filterwarnings("ignore", category=UserWarning, module="matplotlib")

# --- Debug Setup ---
DEBUG = False


def debug_print(s):
    if DEBUG:
        print(s)


# --- Project Root and Data Directories ---
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
DATA_DIR = PROJECT_ROOT / "data"
PROCESSED_DATA_DIR = DATA_DIR / "mimic_3_data" / "processed_data"

# --- Default Paths ---
DEFAULT_FULL_WAVEFORM_DIR = PROCESSED_DATA_DIR / "full_trajectories"
DEFAULT_MED_TENSOR_PATH = PROCESSED_DATA_DIR / "med_tensors"


def group_into_sessions(df, gap_threshold_hours=24):
    """
    Groups a DataFrame of time-series data into sessions based on time gaps.

    Args:
        df (pd.DataFrame): DataFrame with an 'absolute_timestamp' column.
        gap_threshold_hours (int): The number of hours to consider a gap for a new session.

    Returns:
        pd.DataFrame: The input DataFrame with an added 'session_id' column.
    """
    if df.empty:
        return df

    time_diff = df["absolute_timestamp"].diff()
    session_starts = time_diff > pd.Timedelta(hours=gap_threshold_hours)
    df["session_id"] = session_starts.cumsum()

    num_sessions = df["session_id"].nunique()
    if num_sessions > 1:
        print(
            f"  Grouped data into {num_sessions} session(s) based on a {gap_threshold_hours}-hour gap threshold."
        )

    return df


def concatenate_patient_waveforms(hadm_id, full_waveform_dir):
    """
    Finds all waveform files for a patient, concatenates them, and sorts by time.

    Args:
        hadm_id (int): The hospital admission ID.
        full_waveform_dir (Path): Directory containing the full waveform Parquet files.

    Returns:
        pd.DataFrame: A single DataFrame containing all waveform data for the patient,
                      sorted chronologically. Returns an empty DataFrame if no files are found.
    """
    waveform_files = list(full_waveform_dir.glob(f"full_waveform_{hadm_id}_*.parquet"))
    if not waveform_files:
        debug_print(f"No waveform files found for HADM_ID {hadm_id}")
        return pd.DataFrame()

    df_list = [pd.read_parquet(f) for f in waveform_files]
    full_df = pd.concat(df_list, ignore_index=True)

    # Calculate absolute timestamp for each data point
    full_df["absolute_timestamp"] = full_df.apply(
        lambda row: row["record_start_time"]
        + pd.to_timedelta(row["time_seconds"], unit="s"),
        axis=1,
    )

    # Sort the final dataframe by the absolute timestamp
    full_df = full_df.sort_values(by="absolute_timestamp").reset_index(drop=True)

    print(f"  Concatenated {len(waveform_files)} waveform files for HADM_ID {hadm_id}.")
    return full_df


class TrajectoryPlotter:
    """
    A class to process and plot patient trajectory data.
    """

    def __init__(self, hadm_id, full_df, med_df=None, debug=False):
        self.hadm_id = hadm_id
        self.full_df = full_df
        self.med_df = med_df
        self.t0_timestamps = self._extract_t0_timestamps()
        self.debug = debug

    def _debug_print(self, s):
        if self.debug:
            print(s)

    def _extract_t0_timestamps(self):
        """Extracts unique t0 timestamps from the DataFrame."""
        if "t0_timestamps" not in self.full_df.columns:
            return []

        all_t0s = set()
        for t0_obj in self.full_df["t0_timestamps"].dropna():
            if isinstance(t0_obj, (list, np.ndarray)):
                for t0 in t0_obj:
                    all_t0s.add(pd.to_datetime(t0))
        return sorted(list(all_t0s))

    def plot_all_sessions(
        self, phys_signals_to_plot=None, smoothing_neighbors=6, gap_threshold_hours=24
    ):
        """
        Groups data into sessions and plots each one.
        """
        if phys_signals_to_plot is None:
            phys_signals_to_plot = ["HR", "ABP Mean", "ART Mean", "CVP", "RESP", "SpO2"]

        self._group_into_sessions(gap_threshold_hours)

        if self.full_df.empty or "session_id" not in self.full_df.columns:
            print("No data available to plot.")
            return

        for session_id, session_df in self.full_df.groupby("session_id"):
            self._debug_print(f"\n--- Plotting Session {session_id} ---")

            session_start = session_df["absolute_timestamp"].min()
            session_end = session_df["absolute_timestamp"].max()

            session_t0s = [
                t0 for t0 in self.t0_timestamps if session_start <= t0 <= session_end
            ]

            session_med_df = None
            if self.med_df is not None:
                session_med_df = self.med_df[
                    (self.med_df["timestamp"] >= session_start)
                    & (self.med_df["timestamp"] <= session_end)
                ]

            self._plot_session(
                session_df.copy(),
                session_t0s,
                session_med_df,
                phys_signals_to_plot,
                smoothing_neighbors,
                session_id,
            )

    def _group_into_sessions(self, gap_threshold_hours):
        """Adds a 'session_id' column to the main dataframe."""
        if self.full_df.empty:
            return

        time_diff = self.full_df["absolute_timestamp"].diff()
        session_starts = time_diff > pd.Timedelta(hours=gap_threshold_hours)
        self.full_df["session_id"] = session_starts.cumsum()

        num_sessions = self.full_df["session_id"].nunique()
        if num_sessions > 1:
            self._debug_print(
                f"  Grouped data into {num_sessions} session(s) based on a {gap_threshold_hours}-hour gap threshold."
            )

    def _plot_session(
        self,
        session_df,
        t0s,
        med_df,
        phys_signals_to_plot,
        smoothing_neighbors,
        session_id,
    ):
        # This function contains the detailed plotting logic from the original `plot_trajectory` function.
        # It is kept internal to the class.
        plot_trajectory(
            self.hadm_id,
            session_df,
            t0s,
            med_df,
            smoothing_neighbors,
            session_id,
            phys_signals_to_plot=phys_signals_to_plot,
        )


def load_data(hadm_id, full_waveform_dir, med_tensor_path):
    """
    Loads all necessary data for a given hospital admission ID.

    Args:
        hadm_id (int): The hospital admission ID.
        full_waveform_dir (Path): Directory containing the full waveform Parquet files.
        med_tensor_path (Path): Directory containing the medication tensor files.

    Returns:
        tuple: A tuple containing:
            - pd.DataFrame: Combined and processed DataFrame of all waveform data.
            - list: A list of all unique t0 timestamps (as datetime objects).
            - pd.DataFrame: DataFrame of medication data.
    """
    print(f"Loading data for HADM_ID: {hadm_id}")

    # Load and concatenate all waveform data for the patient
    full_df = concatenate_patient_waveforms(hadm_id, full_waveform_dir)
    if full_df.empty:
        raise FileNotFoundError(f"No full waveform files found for HADM_ID {hadm_id}")

    # --- Process Waveform Data ---
    # Extract all unique t0 timestamps from the new list/array format
    all_t0s = set()
    for t0_obj in full_df["t0_timestamps"]:
        # Handle both list and numpy array representations
        if isinstance(t0_obj, (list, np.ndarray)):
            for t0 in t0_obj:
                all_t0s.add(pd.to_datetime(t0))

    t0_timestamps = sorted(list(all_t0s))
    if not t0_timestamps:
        print(
            f"  Warning: No t0 timestamps found in waveform files for HADM_ID {hadm_id}"
        )

    # --- Load and Process Medication Data (Optional) ---
    med_df = None
    med_file = med_tensor_path / f"med_tensor_{hadm_id}.pt"
    if med_file.exists():
        print("  Loading medication data...")
        med_tensors = torch.load(med_file, weights_only=False)
        med_values = med_tensors[0].numpy()
        med_time_minutes = med_tensors[2].numpy()  # Time is in minutes from admission

        # Get the ICU admission time (should be the same for all records of a patient)
        icu_admission_time = full_df["icu_admission_time"].iloc[0]

        # Create absolute timestamps for medication data
        med_timestamps = [
            icu_admission_time + pd.to_timedelta(minutes, unit="m")
            for minutes in med_time_minutes
        ]

        med_names = [f"Med_{i}" for i in range(med_values.shape[1])]
        med_df = pd.DataFrame(med_values, columns=med_names)
        med_df["timestamp"] = med_timestamps
    else:
        print(
            f"  Warning: No medication tensor file found for HADM_ID {hadm_id}. Plotting without medications."
        )

    print("Data loading and processing complete.")
    return full_df, t0_timestamps, med_df


def plot_trajectory(
    hadm_id,
    full_df,
    t0_timestamps,
    med_df,
    smoothing_neighbors=6,
    session_id=0,
    phys_signals_to_plot=None,
):
    """
    Generates and saves a multi-panel plot of the patient trajectory for a single session.
    """
    if phys_signals_to_plot is None:
        phys_signals_to_plot = ["HR", "ABP Mean", "ART Mean", "CVP", "RESP", "SpO2"]

    print(f"Generating plot for session {session_id}...")

    phys_signals = [sig for sig in phys_signals_to_plot if sig in full_df.columns]

    # --- Ensure monotonic time & have a segment key ---
    full_df = full_df.sort_values(
        ["record_start_time", "absolute_timestamp"]
    ).reset_index(drop=True)
    segment_key = "record_start_time"  # treat each record as its own contiguous segment

    # --- Data Cleaning: CVP threshold, others by std-from-median (exact order you requested) ---
    df_processed = full_df[phys_signals].astype(float).copy()
    for signal in phys_signals:
        s = df_processed[signal].copy()

        if signal == "CVP":
            # 1) CVP filter first
            s[s > 50] = np.nan
            debug_print(f"  {signal}: CVP>50 -> NaN, valid={np.isfinite(s).sum()}")
        else:
            # 2) Others: >3*std from median -> NaN
            med = np.nanmedian(s)
            sd = np.nanstd(s, ddof=1)
            if np.isfinite(sd) and sd > 0:
                out_mask = np.abs(s - med) > (3 * sd)
                s[out_mask] = np.nan
                debug_print(f"  {signal}: removed outliers={np.nansum(out_mask)}")
        df_processed[signal] = s

    # --- 3) Manual centered moving average WITHIN each segment; ignore NaNs ---
    neighbors = smoothing_neighbors  # current ±3 => 7-pt window
    win_len = 2 * neighbors + 1
    kernel = np.ones(win_len, dtype=float)

    smoothed_df = pd.DataFrame(
        index=df_processed.index, columns=phys_signals, dtype=float
    )
    # process per record segment to avoid smoothing across gaps
    for signal in phys_signals:
        out_all = np.full(len(df_processed), np.nan, dtype=float)
        for _, seg in (
            full_df[[segment_key, "absolute_timestamp"]]
            .join(df_processed[[signal]])
            .groupby(segment_key, sort=False)
        ):
            vals = seg[signal].to_numpy(dtype=float)

            num = np.convolve(np.nan_to_num(vals, nan=0.0), kernel, mode="same")
            valid = np.isfinite(vals).astype(float)
            den = np.convolve(valid, kernel, mode="same")

            seg_out = np.divide(num, den, out=np.full_like(num, np.nan), where=den > 0)
            out_all[seg.index] = seg_out

        smoothed_df[signal] = out_all
        debug_print(f"  {signal}: valid after smoothing={np.isfinite(out_all).sum()}")

    # Keep time & segment columns for plotting logic
    smoothed_df["absolute_timestamp"] = full_df["absolute_timestamp"]
    smoothed_df[segment_key] = full_df[segment_key]

    # --- Build subplots ---
    n_phys = len(phys_signals)
    if n_phys == 0 and med_df is None:
        print(
            "Error: No physiological signals to plot and no medication data found. Aborting."
        )
        return
    elif n_phys == 0:
        fig, med_ax = plt.subplots(figsize=(24, 6))
        axes = [med_ax]
    else:
        fig, axes = plt.subplots(
            n_phys + (1 if med_df is not None else 0),
            1,
            figsize=(24, 6 * (n_phys + (1 if med_df is not None else 0))),
            sharex=True,
        )
        if n_phys == 1 and med_df is None:
            axes = [axes]
        elif not isinstance(axes, (list, np.ndarray)):
            axes = [axes]

    # --- Plot physiological signals WITHOUT connecting across gaps ---
    for i, signal in enumerate(phys_signals):
        ax = axes[i]
        first = True
        for _, seg in smoothed_df[["absolute_timestamp", signal, segment_key]].groupby(
            segment_key, sort=False
        ):
            x = seg["absolute_timestamp"]
            y = seg[signal].copy()

            # Break lines at big gaps inside the segment: insert NaN at gap starts
            dt = x.diff().dt.total_seconds().to_numpy()
            med_dt = np.nanmedian(dt)
            if np.isfinite(med_dt) and med_dt > 0:
                gap_idx = np.where(dt > 5 * med_dt)[0]  # 5× sampling interval threshold
                if gap_idx.size:
                    y.iloc[gap_idx] = np.nan
                    debug_print(
                        f"  {signal}: inserted {gap_idx.size} NaNs to break large gaps"
                    )

            if np.isfinite(y).any():
                ax.plot(x, y, lw=1.5, label=(signal if first else None))
                first = False

        ax.set_ylabel(signal)
        ax.grid(True, linestyle="--", alpha=0.6)
        if ax.get_legend_handles_labels()[0]:
            ax.legend(loc="upper right")

    # --- Plot medications (unchanged) ---
    if med_df is not None:
        med_ax = axes[-1]
        med_names = [col for col in med_df.columns if col.startswith("Med_")]
        for med_name in med_names:
            active = med_df[med_df[med_name] > 0]
            if not active.empty:
                med_ax.stem(
                    active["timestamp"],
                    active[med_name],
                    label=med_name,
                    basefmt=" ",
                    use_line_collection=True,
                )
        med_ax.set_ylabel("Medication Dosage")
        med_ax.grid(True, linestyle="--", alpha=0.6)
        med_ax.legend(loc="upper right")

    # --- t0 verticals on all axes ---
    if t0_timestamps:
        for ax in axes:
            for j, t0 in enumerate(t0_timestamps):
                label = f't0 @ {t0.strftime("%H:%M")}' if j == 0 else ""
                ax.axvline(x=t0, color="r", linestyle="--", lw=2, label=label)
        # dedupe on top axis
        handles, labels = axes[0].get_legend_handles_labels()
        axes[0].legend(
            dict(zip(labels, handles)).values(),
            dict(zip(labels, handles)).keys(),
            loc="upper right",
        )

    # --- Final formatting & save ---
    axes[-1].xaxis.set_major_formatter(mdates.DateFormatter("%Y-%m-%d\n%H:%M"))
    plt.setp(axes[-1].get_xticklabels(), rotation=0, ha="center")
    fig.suptitle(
        f"Patient Trajectory for HADM_ID: {hadm_id} (Session {session_id})", fontsize=20
    )
    fig.tight_layout(rect=[0, 0, 1, 0.97])

    output_dir = PROJECT_ROOT / "plots"
    output_dir.mkdir(exist_ok=True)
    output_file = output_dir / f"trajectory_{hadm_id}_session_{session_id}.png"
    plt.savefig(output_file, dpi=300)
    print(f"Plot saved to {output_file}")


def main():
    parser = argparse.ArgumentParser(
        description="Plot full patient trajectory with medications."
    )
    parser.add_argument(
        "--hadm_id",
        type=int,
        required=True,
        help="Hospital Admission ID (HADM_ID) to plot.",
    )
    parser.add_argument(
        "--full_waveform_dir",
        type=Path,
        default=DEFAULT_FULL_WAVEFORM_DIR,
        help="Directory containing full waveform Parquet files.",
    )
    parser.add_argument(
        "--med_tensor_path",
        type=Path,
        default=DEFAULT_MED_TENSOR_PATH,
        help="Directory containing medication tensor files.",
    )
    parser.add_argument(
        "--smoothing_neighbors",
        type=int,
        default=6,
        help="Number of neighbors on each side for the moving average (e.g., 3 => 7-point window).",
    )
    parser.add_argument(
        "--gap_threshold_hours",
        type=int,
        default=24,
        help="The number of hours to consider a gap for a new session.",
    )
    parser.add_argument("--debug", action="store_true", help="Enable debug printing.")

    args = parser.parse_args()

    global DEBUG
    if args.debug:
        DEBUG = True

    try:
        full_df, _, med_df = load_data(
            args.hadm_id, args.full_waveform_dir, args.med_tensor_path
        )

        if full_df.empty:
            print("No data available to plot.")
            return

        plotter = TrajectoryPlotter(args.hadm_id, full_df, med_df, debug=DEBUG)
        plotter.plot_all_sessions(
            smoothing_neighbors=args.smoothing_neighbors,
            gap_threshold_hours=args.gap_threshold_hours,
        )

    except FileNotFoundError as e:
        print(f"Error: {e}")
        print(
            "Please ensure the required data has been generated by 'create_ic_p_mimic.py' with the 'save_full_trajectory' flag."
        )
    except Exception as e:
        print(f"An unexpected error occurred: {e}")
        raise


if __name__ == "__main__":
    main()
